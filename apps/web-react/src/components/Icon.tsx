export type IconName = keyof typeof icons

export function isIconName(value: string): value is IconName {
  return Object.hasOwn(icons, value)
}

type IconProps = Omit<LucideProps, 'ref'> & { name: string }

/** Süs ikonudur; anlam taşıyan metin her zaman yanında görünür veya erişilebilir addadır. */
export function Icon({ name, size = 18, strokeWidth = 1.75, ...props }: IconProps) {
  const Component = isIconName(name) ? icons[name] : Circle
  return <Component size={size} strokeWidth={strokeWidth} aria-hidden="true" {...props} />
}
